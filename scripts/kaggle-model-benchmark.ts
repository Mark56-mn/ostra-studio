#!/usr/bin/env bun
/**
 * Create the Ostra model-benchmark notebook and (optionally) push it to Kaggle.
 *
 * NOTHING here simulates: the notebook, when run on Kaggle's GPU, really loads each candidate model
 * on the real device, really times time-to-first-token over a real generate() call, and really
 * reports peak VRAM from torch.cuda. Its one output file (ostra-model-benchmark.json) is the
 * measured truth — the Ostra backend picks the strongest model the free GPU can actually serve.
 *
 * Re-run the SAME command after the run finishes to re-push; each push versions the notebook and
 * keeps the previous results in its version history. One CLI, no flags to remember:
 *
 *   bun scripts/kaggle-model-benchmark.ts --apply     # push (Kaggle auto-runs version 1)
 *   bun scripts/kaggle-model-benchmark.ts --token=2   # push as that account instead
 *   bun scripts/kaggle-model-benchmark.ts --dump      # print the cells, touch nothing
 *   bun scripts/kaggle-model-benchmark.ts --model=Qwen/Qwen3-4B --model=Qwen/Qwen3-1.7B --apply
 *
 * Exit codes: 0 ok | 2 NOT_CONFIGURED | 3 AUTH_FAILED/unreachable | 1 other failure
 */

import { AGENT_ROSTER, kaggleConfig, kaggleApiTokens, getKaggleAuthHeader, parseKernelRef } from "../packages/shared/src/index";
import { probeAccount } from "./kaggle-agent-notebook.js";

const KAGGLE_API = "https://www.kaggle.com/api/v1";
const BENCHMARK_SLUG = "ostra-model-benchmark";
const BENCHMARK_TITLE = "Ostra model benchmark";

/** Default shortlist, strongest-first: what a free T4/P100 could plausibly serve for chat. */
export const DEFAULT_BENCHMARK_MODELS = [
  "Qwen/Qwen3-4B-Instruct-2507",
  "Qwen/Qwen3-4B",
  "Qwen/Qwen3-1.7B",
] as const;

export interface BenchmarkModelResult {
  model: string;
  loaded: boolean;
  load_seconds: number | null;
  peak_vram_gib: number | null;
  prompt_tokens: number;
  gen_tokens: number;
  gen_seconds: number | null;
  tokens_per_second: number | null;
  error: string | null;
}

function pyCell(source: string) {
  return {
    cell_type: "code" as const,
    execution_count: null,
    metadata: {},
    outputs: [],
    source: source.split("\n").map((l, i, all) => (i === all.length - 1 ? l : `${l}\n`)),
  };
}

function mdCell(source: string) {
  return {
    cell_type: "markdown" as const,
    metadata: {},
    source: source.split("\n").map((l, i, all) => (i === all.length - 1 ? l : `${l}\n`)),
  };
}

/** The benchmark cells. Pure — same input always yields the same notebook. */
export function buildBenchmarkNotebook(models: readonly string[]) {
  const listLiteral = JSON.stringify(models);
  const cells = [
    mdCell(
      [
        "# Ostra Studio — model benchmark (real GPU measurements)",
        "",
        "Generated by `scripts/kaggle-model-benchmark.ts`. Run the whole notebook on a GPU accelereator.",
        "It loads each candidate model on the real device, times time-to-first-token and generation",
        "throughput, and records peak VRAM. Results land in `ostra-model-benchmark.json` — no mock",
        "numbers anywhere; a model that fails to load is reported as failed with its real error.",
      ].join("\n")
    ),
    pyCell(
      [
        "# ── Ostra Studio: benchmark setup (managed cell) ──",
        "import subprocess, sys",
        "subprocess.run(",
        "    [sys.executable, \"-m\", \"pip\", \"install\", \"-q\",",
        "     \"transformers>=4.51\", \"accelerate\", \"sentencepiece\", \"protobuf\"],",
        "    check=True,",
        ")",
        "print(\"[ostra] benchmark dependencies installed\")",
      ].join("\n")
    ),
    pyCell(
      [
        "# ── Ostra Studio: benchmark environment (managed cell) ──",
        "import json, time",
        "",
        "import torch",
        "",
        "MODELS = " + listLiteral,
        "PROMPT = \"You are the Script AI of a manhwa studio. In two vivid sentences, introduce a rain-soaked night market where a deal is about to go wrong.\"",
        "GEN_TOKENS = 64",
        "",
        "if not torch.cuda.is_available():",
        "    raise RuntimeError(\"no CUDA device — attach a GPU accelerator to this notebook and re-run\")",
        "",
        "GPU_NAME = torch.cuda.get_device_name(0)",
        "VRAM_TOTAL_GIB = torch.cuda.get_device_properties(0).total_memory / (1024 ** 3)",
        "print(f\"[ostra] GPU: {GPU_NAME} ({VRAM_TOTAL_GIB:.1f} GiB)\")",
        "",
        "RESULTS = []",
      ].join("\n")
    ),
    pyCell(
      [
        "# ── Ostra Studio: per-model measurement (managed cell) ──",
        "from transformers import AutoModelForCausalLM, AutoTokenizer",
        "",
        "for MODEL_ID in MODELS:",
        "    result = {\"model\": MODEL_ID, \"loaded\": False, \"load_seconds\": None,",
        "              \"peak_vram_gib\": None, \"prompt_tokens\": 0, \"gen_tokens\": 0,",
        "              \"gen_seconds\": None, \"tokens_per_second\": None, \"error\": None}",
        "    print(f\"\\\\n[ostra] === {MODEL_ID} ===\", flush=True)",
        "    try:",
        "        if torch.cuda.is_available():",
        "            torch.cuda.empty_cache()",
        "            torch.cuda.reset_peak_memory_stats()",
        "        t0 = time.perf_counter()",
        "        tokenizer = AutoTokenizer.from_pretrained(MODEL_ID)",
        "        model = AutoModelForCausalLM.from_pretrained(",
        "            MODEL_ID, torch_dtype=\"auto\", device_map=\"auto\"",
        "        )",
        "        model.eval()",
        "        result[\"load_seconds\"] = round(time.perf_counter() - t0, 2)",
        "        result[\"loaded\"] = True",
        "        result[\"peak_vram_gib\"] = round(torch.cuda.max_memory_allocated() / (1024 ** 3), 2)",
        "",
        "        inputs = tokenizer(PROMPT, return_tensors=\"pt\").to(model.device)",
        "        result[\"prompt_tokens\"] = int(inputs[\"input_ids\"].shape[1])",
        "        t1 = time.perf_counter()",
        "        with torch.no_grad():",
        "            generated = model.generate(",
        "                **inputs, max_new_tokens=GEN_TOKENS, do_sample=False,",
        "                return_dict_in_generate=True, output_scores=False,",
        "            )",
        "        result[\"gen_tokens\"] = int(generated.sequences[0].shape[0] - inputs[\"input_ids\"].shape[1])",
        "        gen_seconds = time.perf_counter() - t1",
        "        result[\"gen_seconds\"] = round(gen_seconds, 2)",
        "        if gen_seconds > 0 and result[\"gen_tokens\"] > 0:",
        "            result[\"tokens_per_second\"] = round(result[\"gen_tokens\"] / gen_seconds, 2)",
        "        preview = tokenizer.decode(",
        "            generated.sequences[0][inputs[\"input_ids\"].shape[1]:], skip_special_tokens=True",
        "        )",
        "        print(f\"[ostra] load={result['load_seconds']}s vram={result['peak_vram_gib']}GiB \"",
        "              f\"tok/s={result['tokens_per_second']}\")",
        "        print(\"[ostra] sample:\", preview[:160].replace(\"\\\\n\", \" \"))",
        "        del model, tokenizer",
        "    except Exception as exc:",
        "        result[\"error\"] = f\"{exc.__class__.__name__}: {exc}\"",
        "        print(f\"[ostra] {MODEL_ID} FAILED: {result['error']}\", flush=True)",
        "    RESULTS.append(result)",
        "",
        "if torch.cuda.is_available():",
        "    torch.cuda.empty_cache()",
      ].join("\n")
    ),
    pyCell(
      [
        "# ── Ostra Studio: report (managed cell) ──",
        "loaded = [r for r in RESULTS if r[\"loaded\"] and r[\"tokens_per_second\"]]",
        "ranking = sorted(loaded, key=lambda r: r[\"tokens_per_second\"], reverse=True)",
        "print(\"\\\\n=== Ostra model benchmark (real measurements) ===\")",
        "print(f\"GPU: {GPU_NAME} — {VRAM_TOTAL_GIB:.1f} GiB\")",
        "for i, r in enumerate(ranking, 1):",
        "    print(f\"{i}. {r['model']}: {r['tokens_per_second']} tok/s, \"",
        "          f\"load {r['load_seconds']}s, peak VRAM {r['peak_vram_gib']} GiB\")",
        "for r in RESULTS:",
        "    if not r[\"loaded\"]:",
        "        print(f\"FAILED: {r['model']}: {r['error']}\")",
        "if ranking:",
        "    print(f\"\\\\nRECOMMENDED: {ranking[0]['model']}\")",
        "",
        "with open(\"ostra-model-benchmark.json\", \"w\", encoding=\"utf-8\") as fh:",
        "    json.dump({\"gpu\": GPU_NAME, \"vram_total_gib\": round(VRAM_TOTAL_GIB, 2),",
        "               \"generated_at\": time.strftime(\"%Y-%m-%dT%H:%M:%SZ\", time.gmtime()),",
        "               \"results\": RESULTS, \"recommended\": ranking[0][\"model\"] if ranking else None},",
        "              fh, indent=2, sort_keys=True)",
        "print(\"[ostra] wrote ostra-model-benchmark.json\")",
      ].join("\n")
    ),
  ];
  const withIds = cells.map((c, i) => ({ ...c, id: `ostra-benchmark-${i}` }));
  return {
    nbformat: 4,
    nbformat_minor: 5,
    metadata: {
      kernelspec: { display_name: "Python 3", language: "python", name: "python3" },
      language_info: { name: "python", version: "3.12" },
    },
    cells: withIds,
  };
}

/**
 * Which models a Kaggle GPU class could realistically host, from the roster's own model defaults.
 * Hosted roles (the Management Team) are skipped on purpose: they run on an API, never on a T4.
 */
export function rosterModels(): string[] {
  return [...new Set(AGENT_ROSTER.filter((a) => a.runtime === "kaggle").map((a) => a.model))];
}

type Args = { apply: boolean; dump: boolean; owner: string | null; slug: string | null; tokenSel: string | null; models: string[] };

function parseArgs(argv: string[]): Args {
  const models = argv
    .filter((a) => a.startsWith("--model="))
    .map((a) => a.slice("--model=".length).trim())
    .filter(Boolean);
  const ownerArg = argv.find((a) => a.startsWith("--owner="))?.slice("--owner=".length).trim();
  const slugArg = argv.find((a) => a.startsWith("--slug="))?.slice("--slug=".length).trim();
  const tokenArg = argv.find((a) => a.startsWith("--token="))?.slice("--token=".length).trim();
  return {
    apply: argv.includes("--apply"),
    dump: argv.includes("--dump"),
    owner: ownerArg || null,
    slug: slugArg || null,
    tokenSel: tokenArg || null,
    models: models.length > 0 ? models : [...DEFAULT_BENCHMARK_MODELS],
  };
}

async function pushKernel(authHeader: string, owner: string, source: string, slug: string): Promise<number> {
  const ref = `${owner}/${slug}`;
  const res = await fetch(`${KAGGLE_API}/kernels/push`, {
    method: "POST",
    headers: { Authorization: authHeader, "Content-Type": "application/json" },
    body: JSON.stringify({
      slug: ref,
      newTitle: BENCHMARK_TITLE,
      text: source,
      language: "python",
      kernelType: "notebook",
      isPrivate: true,
      enableInternet: true,
      enableGpu: true,
      enableTpu: false,
    }),
    signal: AbortSignal.timeout(30000),
  });
  const raw = await res.text().catch(() => "");
  console.log(`  POST /kernels/push (${ref}) -> HTTP ${res.status}`);
  if (!res.ok) {
    console.log(`  body: ${raw.slice(0, 300)}`);
    console.log("  RESULT: PUSH FAILED — the notebook was not created.");
    return res.status === 401 || res.status === 403 ? 3 : 1;
  }
  let parsed: Record<string, unknown> = {};
  try { parsed = raw ? (JSON.parse(raw) as Record<string, unknown>) : {}; } catch { parsed = {}; }
  console.log(`  versionNumber=${String(parsed.versionNumber)} url=${String(parsed.url ?? "(none)")}`);
  console.log("  RESULT: PUSHED — run it on a GPU accelerator; the output file carries the measurements.");
  console.log(`  Read results: bun scripts/kaggle-live-check.ts --kernel-ref=${String(parsed.url ?? ref).split("/code/").pop() ?? ref} --logs`);
  return 0;
}

export async function main(argv = process.argv): Promise<number> {
  console.log("=== Ostra Studio: Kaggle model benchmark ===");
  console.log(`at ${new Date().toISOString()}`);
  console.log("");

  const args = parseArgs(argv);
  const tokens = kaggleApiTokens();
  const cfg = kaggleConfig();

  console.log(`  candidates: ${args.models.join(", ")}`);
  const notebook = buildBenchmarkNotebook(args.models);
  const source = JSON.stringify(notebook);
  console.log(`  cells: ${notebook.cells.length}, source: ${source.length} chars`);

  if (args.dump) {
    notebook.cells.forEach((c, i) => {
      const src = Array.isArray(c.source) ? c.source.join("") : String(c.source);
      console.log(`\\n===== cell ${i} [${c.cell_type}] =====`);
      console.log(src);
    });
    console.log("\\n  RESULT: DRY RUN — re-run with --apply to push the notebook.");
    return 0;
  }
  if (!args.apply) {
    console.log("  RESULT: DRY RUN — re-run with --apply to push the notebook.");
    return 0;
  }
  if (tokens.length === 0) {
    console.log("  RESULT: NOT_CONFIGURED — no KAGGLE_API_TOKEN / KAGGLE_API_TOKEN_<n> is set.");
    return 2;
  }

  let index = 0;
  if (args.tokenSel && args.tokenSel !== "all") {
    const n = Number.parseInt(args.tokenSel, 10);
    if (!Number.isInteger(n) || n < 1 || n > tokens.length) {
      console.log(`  RESULT: ERROR — --token=${args.tokenSel} is out of range: ${tokens.length} token(s) configured`);
      return 2;
    }
    index = n - 1;
  }
  const authHeader = getKaggleAuthHeader(tokens[index]);
  const probe = await probeAccount(authHeader);
  if (!probe.authenticated) {
    console.log(`  account probe FAILED for token #${index + 1} (${probe.error ?? "token rejected"})`);
    return 3;
  }
  const kernelRef = cfg.kernelRef ?? null;
  const refOwner = kernelRef ? parseKernelRef(kernelRef).owner : null;
  const owner = probe.owner ?? args.owner ?? refOwner ?? null;
  if (!owner) {
    console.log(`  token #${index + 1} is valid but its account owns nothing listable; re-run with --owner=<account>.`);
    return 1;
  }
  if (probe.owner && owner !== probe.owner) {
    console.log(`  REFUSING — token #${index + 1} owns "${probe.owner}" but the push targets "${owner}". Re-run with --owner=${probe.owner}.`);
    return 1;
  }
  return pushKernel(authHeader, owner, source, args.slug || BENCHMARK_SLUG);
}

if (import.meta.main) {
  main()
    .then((code) => { process.exitCode = code; })
    .catch((e) => { console.error("unexpected failure:", e instanceof Error ? e.message : String(e)); process.exitCode = 1; });
}
